/** Case colours we stock — Clear + finishes that match each model */
export function getCaseColorsForModel(model: string): string[] {
  const finishes = [...(IPHONE_MODEL_COLORS[model] ?? [])]
  if (!finishes.includes('Clear')) finishes.unshift('Clear')
  return finishes
}

export function getBackGlassColorsForModel(model: string): string[] {
  return [...(IPHONE_MODEL_COLORS[model] ?? [])]
}

